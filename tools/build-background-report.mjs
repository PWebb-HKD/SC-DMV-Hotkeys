/** Generate the postback hook from the canonical portal DOM function. */
import {readFileSync,writeFileSync} from 'node:fs';
import {pageOperation} from '../extension/page.js';
const wrapper = `
// Only a query tab armed by the worker has this expiring marker.
try {if(Number(sessionStorage.getItem('__scDmvBackgroundReport'))>Date.now())pageOperation('startBackgroundReport',{persistent:true});}catch{}
`;
const source = '// Generated by tools/build-background-report.mjs; edit page.js and the generator.\n'+pageOperation.toString()+'\n'+wrapper;
const destination=new URL('../extension/background-report.js',import.meta.url);
if(process.argv.includes('--check')) {
  if(readFileSync(destination,'utf8')!==source)throw new Error('Run node tools/build-background-report.mjs after changing page.js.');
} else writeFileSync(destination,source);
