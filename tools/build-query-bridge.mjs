/** Generate the MAIN-world iframe adapter from the canonical portal DOM function. */
import {readFileSync,writeFileSync} from 'node:fs';
import {pageOperation} from '../extension/page.js';
const wrapper = `
(() => {
  // Preserve the owned Download handoff across ASP.NET postbacks. The marker
  // belongs to this tab's sessionStorage; ordinary DMV tabs have no marker.
  try {if(Number(sessionStorage.getItem('__scDmvBackgroundReport'))>Date.now())pageOperation('startBackgroundReport',{persistent:true});}catch{}
  if(window===top)return;
  let owner,token;
  window.addEventListener('message',async event=>{
    const m=event.data;
    if(event.source===window && m?.target==='scdmv-bridge-origin' && !owner && /^chrome-extension:\\/\\/[a-p]{32}$/.test(m.origin)) {owner=m.origin;parent.postMessage({target:'scdmv-host',type:'available'},owner);return;}
    if(!owner||event.source!==parent||event.origin!==owner||m?.target!=='scdmv-query')return;
    if(m.type==='init') {
      token=m.token;
      const ready=()=>{if(token===m.token)parent.postMessage({target:'scdmv-host',type:'ready',token,url:location.href},owner);};
      if(document.readyState==='complete')ready();else window.addEventListener('load',ready,{once:true});
      return;
    }
    if(!token||m.token!==token||m.type!=='operation')return;
    try {const value=await pageOperation(m.op,m.args);parent.postMessage({target:'scdmv-host',type:'reply',token,id:m.id,value},owner);}
    catch(error){parent.postMessage({target:'scdmv-host',type:'reply',token,id:m.id,error:error.message},owner);}
  });
  window.addEventListener('beforeunload',()=>{if(owner&&token)parent.postMessage({target:'scdmv-host',type:'unloading',token},owner);});
})();
`;
const source = '// Generated by tools/build-query-bridge.mjs; edit page.js and the generator.\n'+pageOperation.toString()+'\n'+wrapper;
const destination=new URL('../extension/offscreen-main.js',import.meta.url);
if(process.argv.includes('--check')) {
  if(readFileSync(destination,'utf8')!==source)throw new Error('Run node tools/build-query-bridge.mjs after changing page.js.');
} else writeFileSync(destination,source);
